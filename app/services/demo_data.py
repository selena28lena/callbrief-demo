def _actions_for(analysis: dict, client: str, contact: str, manager: str) -> list[dict]:
    """Готовые действия: развёрнутый комментарий в CRM, задача, следующий контакт."""
    needs = "; ".join(n["text"] for n in analysis.get("needs", [])) or "не выявлена"
    objections = "; ".join(o["text"] for o in analysis.get("objections", [])) or "не озвучены"
    agreements = "; ".join(a["text"] for a in analysis.get("agreements", [])) or "нет"
    risks = "; ".join(r["text"] for r in analysis.get("risks", [])) or "нет"
    step = (analysis.get("next_steps") or [{}])[0]
    comment = (
        f"{client} · {contact}\n"
        f"Итог звонка: {analysis.get('outcome', 'интерес')}\n\n"
        f"Суть: {analysis['summary']}\n\n"
        f"Потребность клиента: {needs}.\n"
        f"Возражения и сомнения: {objections}.\n"
        f"Договорённости: {agreements}.\n"
        f"Риски: {risks}.\n"
        f"Следующий шаг: {step.get('action', 'не назначен')}"
        + (f" (срок: {step['deadline']})" if step.get("deadline") else "") + ".\n\n"
        f"Менеджер: {manager}. Комментарий подготовлен CallBrief по расшифровке разговора."
    )
    items = [{"type": "crm_comment", "payload": {"text": comment}}]
    if step.get("action"):
        items.append({"type": "task", "payload": {
            "title": step["action"], "deadline": step.get("deadline") or "завтра", "owner": manager}})
        items.append({"type": "next_contact", "payload": {"when": step.get("deadline") or "через 2 дня"}})
    else:
        items.append({"type": "task", "payload": {
            "title": f"Назначить следующий контакт с «{client}»", "deadline": "сегодня", "owner": manager}})
    return items


def seed(reset: bool = True, calls_count: int = 48) -> dict:
    """Наполняет базу демо-звонками. Возвращает краткую статистику."""
    rnd = random.Random(20260916)
    if reset:
        clear()
    store.set_setting("demo_cleared", "0")

    users = [u for u in store.users() if u["role"] == "manager"]
    if not users:
        return {"calls": 0}

    client_ids = {}
    for name, contact, phone, industry in CLIENTS:
        owner = rnd.choice(users)
        client_id = db.execute(
            "INSERT INTO clients (name, company, phone, industry, stage, owner_id, status) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (contact, name, phone, industry, rnd.choice(["Новая", "В работе", "Переговоры"]), owner["id"], "active"),
        )
        client_ids[name] = client_id

    pool = []
    for func, weight in SCENARIOS:
        pool += [func] * weight

    now = datetime.now()
    created = 0
    for i in range(calls_count):
        scenario = rnd.choice(pool)
        client_name, contact, phone, industry = CLIENTS[i % len(CLIENTS)]
        manager = users[i % len(users)]
        transcript, analysis, scores, coach, best = scenario(client_name, contact, industry, manager["name"])

        started = now - timedelta(days=rnd.randint(0, 20), hours=rnd.randint(0, 9), minutes=rnd.randint(0, 59))
        duration = rnd.randint(95, 620)
        total = round(sum(scores.values()) / len(scores), 1)
        has_next = bool(analysis.get("next_steps"))
        level, reason = sev.compute(analysis, total, has_next)
        risks = analysis.get("risks") or []
        risk_level = min((r["level"] for r in risks), key=lambda x: {"high": 0, "medium": 1, "low": 2}[x], default="none")

        call_id = store.create_call(
            client_id=client_ids[client_name],
            user_id=manager["id"],
            title=f"Входящий звонок · {client_name}",
            started_at=started.strftime("%Y-%m-%d %H:%M:%S"),
            duration=duration,
            source="demo",
            transcript=transcript,
            model="demo",
            outcome=analysis.get("outcome"),
            risk_level=risk_level,
            severity=level,
            severity_reason=reason,
            score=total,
            has_next_step=int(has_next),
            is_demo=1,
            status="analyzed",
        )
        confirmed = sum(1 for key in ("agreements", "next_steps", "risks", "recommendations")
                        for item in analysis.get(key, []) if item.get("verified"))
        total_quotes = sum(len(analysis.get(key, [])) for key in ("agreements", "next_steps", "risks", "recommendations"))
        store.save_analysis(call_id, analysis, confirmed, total_quotes, "demo")
        store.save_scorecard(call_id, {
            "criteria": [{"name": name, "score": score,
                          "comment": "Сильная сторона" if score >= 8 else "Зона роста" if score <= 4 else "Норма"}
                         for name, score in scores.items()],
            "strengths": [c for c, s in scores.items() if s >= 8],
            "blockers": [c for c, s in scores.items() if s <= 4],
            "growth_area": min(scores, key=scores.get),
        }, total, "demo")
        if coach:
            store.replace_coach_items(call_id, manager["id"], coach)
        if best:
            store.replace_best_moments(call_id, manager["id"], best)
        store.replace_actions(call_id, _actions_for(analysis, client_name, contact, manager["name"]))
        if rnd.random() < 0.45:
            for action in store.actions(call_id=call_id):
                store.update_action(action["id"], status="applied", applied_at=started.strftime("%Y-%m-%d %H:%M:%S"))
            store.update_call(call_id, status="saved")   # всё отправлено в CRM — звонок сохранён
        created += 1

    store.set_setting("demo_seeded", True)
    return {"calls": created, "clients": len(CLIENTS), "managers": len(users)}


def clear() -> None:
    """Удаляет все демо-звонки и связанные с ними данные."""
    db.execute("DELETE FROM calls WHERE is_demo = 1")
    store.set_setting("demo_cleared", "1")
    db.execute("DELETE FROM clients WHERE id NOT IN (SELECT client_id FROM calls WHERE client_id IS NOT NULL)")
    db.execute("DELETE FROM analyses WHERE call_id NOT IN (SELECT id FROM calls)")
    db.execute("DELETE FROM scorecards WHERE call_id NOT IN (SELECT id FROM calls)")
    db.execute("DELETE FROM coach_items WHERE call_id NOT IN (SELECT id FROM calls)")
    db.execute("DELETE FROM best_moments WHERE call_id NOT IN (SELECT id FROM calls)")
    db.execute("DELETE FROM actions WHERE call_id NOT IN (SELECT id FROM calls)")
    store.set_setting("demo_seeded", False)
